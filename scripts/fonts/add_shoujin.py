"""
Turns a licensed 瘦金体 (Slender Gold) font file into the web font the site and the package art
use for inscriptions and title slips:

    python3 scripts/fonts/add_shoujin.py <path to the .ttf or .otf you licensed>

It slices the font by Unicode range (slicer.py) into public/fonts/shoujin/sj-NNN.woff2 with a
stylesheet beside them, public/fonts/shoujin/shoujin.css (family "PA Shoujin"). That folder is
git-ignored: a commercial font must not be published with the source. When the stylesheet is
there at build time, next.config.ts switches the inscription face to it; to serve it from
elsewhere, set NEXT_PUBLIC_SHOUJIN_FONT_URL to its address instead.

Check that your licence covers web embedding and printed products (FounderType 方正瘦金书 and
Hanyi 汉仪瘦金书 sell such licences; their free downloads are for personal use only).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from slicer import ROOT, slice_font  # noqa: E402

OUT = ROOT / "public" / "fonts" / "shoujin"


def main(src):
    data = Path(src).read_bytes()
    # relative URLs: the slices sit beside the stylesheet wherever it is served from
    rules = slice_font(data, "PA Shoujin", OUT, "sj", "", hinting=False)
    (OUT / "shoujin.css").write_text(
        "/* 瘦金体 (licensed; not in the repository), sliced by Unicode range so a page loads only the\n"
        "   characters it shows. Generated by scripts/fonts/add_shoujin.py. */\n" + "\n".join(rules) + "\n",
        "utf-8",
    )
    print("wrote", OUT / "shoujin.css")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1])
